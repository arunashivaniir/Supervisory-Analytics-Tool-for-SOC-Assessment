def safe_member_name(name: str) -> str:
    """Validate an archive member name and return a safe relative path.

    Rejects absolute paths, Windows drive letters, ``..`` traversal, control
    characters, over-long names and over-deep nesting. Returns a normalised
    POSIX-style relative path that is guaranteed to stay inside the extraction
    directory.

    Raises:
        UnsafeArchiveError: the member name is not acceptable.
    """

    raw = str(name or "").strip()

    if not raw:
        raise UnsafeArchiveError("Archive member has an empty name")

    if "\x00" in raw:
        raise UnsafeArchiveError(
            f"Archive member name contains a null byte: {name!r}"
        )

    if any(ord(character) < 32 for character in raw):
        raise UnsafeArchiveError(
            f"Archive member name contains control characters: {name!r}"
        )

    # Treat a backslash as a separator for validation purposes: a Windows-style
    # name is only accepted if every one of its components is also safe.
    candidate = raw.replace("\\", "/")

    if candidate.startswith("/") or _WINDOWS_DRIVE.match(candidate):
        raise UnsafeArchiveError(
            f"Archive member uses an absolute path: {name!r}"
        )

    parts = [part for part in candidate.split("/") if part not in ("", ".")]

    if not parts:
        raise UnsafeArchiveError(
            f"Archive member does not name a file: {name!r}"
        )

    if any(part == ".." for part in parts):
        raise UnsafeArchiveError(
            f"Archive member attempts path traversal: {name!r}"
        )

    if len(parts) > MAX_MEMBER_PATH_DEPTH:
        raise UnsafeArchiveError(
            f"Archive member nesting is too deep ({len(parts)} levels): "
            f"{name!r}"
        )

    for part in parts:
        if len(part) > MAX_MEMBER_NAME_LENGTH:
            raise UnsafeArchiveError(
                f"Archive member name component is too long: {name!r}"
            )

    return "/".join(parts)


def validate_package(
    archive_path: Union[str, Path],
    max_members: int = MAX_ARCHIVE_MEMBERS,
    max_total_bytes: int = MAX_ARCHIVE_TOTAL_BYTES,
    max_member_bytes: int = MAX_ARCHIVE_MEMBER_BYTES,
) -> list:
    """Validate every member of a ZIP evidence package before any extraction.

    Returns a list of ``(ZipInfo, safe_relative_name)`` pairs. Raises before a
    single byte is written if anything is unsafe.

    Raises:
        UnsafeArchiveError: malformed archive, unsafe member, or a package that
            exceeds the member/byte limits.
    """

    source = Path(archive_path).expanduser()

    if not zipfile.is_zipfile(source):
        raise UnsafeArchiveError(f"Not a valid ZIP evidence package: {source}")

    try:
        with zipfile.ZipFile(source) as archive:
            bad_crc = archive.testzip()
    except (zipfile.BadZipFile, OSError, RuntimeError) as error:
        raise UnsafeArchiveError(
            f"Evidence package could not be opened: {source} ({error})"
        ) from error

    if bad_crc is not None:
        raise UnsafeArchiveError(
            f"Evidence package contains a corrupt member: {bad_crc!r}"
        )

    with zipfile.ZipFile(source) as archive:
        entries = archive.infolist()

        if len(entries) > max_members:
            raise UnsafeArchiveError(
                f"Evidence package declares {len(entries)} members, which "
                f"exceeds the limit of {max_members}"
            )

        declared_total = 0
        accepted: list = []

        for info in entries:
            if info.flag_bits & _ENCRYPTED_FLAG:
                raise UnsafeArchiveError(
                    f"Encrypted archive members are not supported: {info.filename!r}"
                )

            mode = info.external_attr >> 16

            if mode and stat.S_ISLNK(mode):
                raise UnsafeArchiveError(
                    f"Archive member is a symbolic link: {info.filename!r}"
                )

            safe = safe_member_name(info.filename)

            if info.is_dir():
                accepted.append((info, safe.rstrip("/")))
                continue

            if info.file_size > max_member_bytes:
                raise UnsafeArchiveError(
                    f"Archive member exceeds the {max_member_bytes} byte "
                    f"limit: {info.filename!r}"
                )

            declared_total += info.file_size

            if declared_total > max_total_bytes:
                raise UnsafeArchiveError(
                    "Evidence package exceeds the "
                    f"{max_total_bytes} byte uncompressed limit"
                )

            accepted.append((info, safe))

    return accepted


def _extract_package(
    archive_path: Union[str, Path],
    destination: Union[str, Path],
    accepted: Sequence,
) -> list:
    """Extract pre-validated members, one file at a time, inside destination.

    ``extractall`` is deliberately not used. Each member is written to a path
    produced by :func:`safe_member_name` and re-resolved against the extraction
    root, and each destination is opened in exclusive-create mode.
    """

    root = Path(destination).expanduser().resolve()
    root.mkdir(parents=True, exist_ok=True)

    written: list = []

    with zipfile.ZipFile(Path(archive_path).expanduser()) as archive:
        for info, safe in accepted:
            target = resolve_within(root, safe)

            if info.is_dir():
                target.mkdir(parents=True, exist_ok=True)
                continue

            target.parent.mkdir(parents=True, exist_ok=True)

            if target.exists():
                raise EvidenceConflictError(
                    f"Refusing to overwrite an extracted member: {target}"
                )

            written_bytes = 0

            with archive.open(info) as reader:
                with target.open("xb") as writer:
                    while True:
                        chunk = reader.read(DEFAULT_CHUNK_SIZE)

                        if not chunk:
                            break

                        written_bytes += len(chunk)

                        writer.write(chunk)

            written.append((safe, target, written_bytes))

    return written


