"""
SAT-SA Evidence Intake.

This is the entry point of the evidence trust chain. It receives submitted
evidence (CSV, JSON, ZIP or any other regular file), establishes its identity
and provenance, and produces two physically separate artefacts:

    data/evidence/
        originals/<evidence_id>/<file>      preserved original, write-protected
        manifests/<evidence_id>.manifest.json
        provenance/<evidence_id>.provenance.json
        working/<evidence_id>/dataset/<file> controlled analysis copy
        working/<evidence_id>/package/...   validated extracted members

The analytical SAT-SA pipeline is expected to consume the *working copy*, never
the preserved original. Intake itself performs no SOC analysis and has no
knowledge of alerts, investigations, assets or any other SOC concept -- it only
establishes evidence integrity and provenance.

Controls implemented here:

* No network, cloud, external API or AI dependency. Pure local stdlib.
* Submitted files are only ever read as bytes. Nothing is executed, imported,
  evaluated, or treated as a command.
* Archives are never expanded with ``extractall``. Every member name is
  validated and resolved inside the workspace before anything is written.
* Absolute paths, drive letters, ``..`` traversal, symlink members, encrypted
  members and decompression bombs are rejected.
* Existing evidence is never overwritten; re-registering the same submission
  raises :class:`EvidenceConflictError`.
* Only metadata (names, sizes, digests, timestamps) is recorded. File contents
  are never logged or duplicated into the records.

Explicitly *not* claimed: locally stored evidence is not made physically
immutable, tamper-proof or administrator-proof. A preserved original is
write-protected at application level and registered with a SHA-256 fingerprint;
detection of later changes comes from comparing bytes against that fingerprint
before analysis. A privileged filesystem user can still modify both the evidence
and the local manifest. See ``docs/evidence_integrity.md``.
"""

