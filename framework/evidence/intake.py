def _build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="python -m framework.evidence.intake",
        description=(
            "SAT-SA evidence intake: register submitted evidence, verify its "
            "integrity, and create a controlled analysis copy."
        ),
    )

    subparsers = parser.add_subparsers(dest="command")

    intake_parser = subparsers.add_parser(
        "intake",
        help="register a submitted CSV/JSON/ZIP file",
    )
    _add_intake_arguments(intake_parser)

    verify_parser = subparsers.add_parser(
        "verify",
        help="re-verify registered evidence against its manifest",
    )
    verify_parser.add_argument(
        "evidence_id",
        nargs="?",
        help="evidence identifier; omit to verify every registration",
    )
    _add_common_arguments(verify_parser)

    return parser


def _add_common_arguments(parser: argparse.ArgumentParser) -> None:
    parser.add_argument(
        "--root",
        default=DEFAULT_WORKSPACE_ROOT,
        help=f"evidence workspace directory (default: {DEFAULT_WORKSPACE_ROOT})",
    )


def _add_intake_arguments(parser: argparse.ArgumentParser) -> None:
    _add_common_arguments(parser)

    parser.add_argument("file", help="path to the submitted evidence file")

    parser.add_argument(
        "--source-identifier",
        default=None,
        help="submitting entity identifier, if supplied",
    )
    parser.add_argument(
        "--assessment-period",
        default=None,
        help="reporting period covered by the evidence, if supplied",
    )
    parser.add_argument(
        "--submitted-by",
        default=None,
        help="name of the submitter, if supplied",
    )
    parser.add_argument(
        "--received-channel",
        default=None,
        help="how the evidence was received, if supplied",
    )
    parser.add_argument(
        "--no-extract",
        action="store_true",
        help="register a ZIP package without extracting its members",
    )
    parser.add_argument(
        "--allow-duplicate",
        action="store_true",
        help="register byte-identical evidence that is already in the store",
    )
    parser.add_argument(
        "--json",
        action="store_true",
        help="emit the intake record as JSON instead of a summary",
    )


def _run_intake(args: argparse.Namespace) -> int:
    intake = EvidenceIntake(root=args.root)

    record = intake.intake(
        args.file,
        source_identifier=args.source_identifier,
        assessment_period=args.assessment_period,
        submitted_by=args.submitted_by,
        received_channel=args.received_channel,
        extract_package=not args.no_extract,
        allow_duplicate=args.allow_duplicate,
    )

    if args.json:
        import json

        print(json.dumps(record.to_dict(), indent=2))

        return 0 if record.verified else 1

    print("[+] Evidence intake started")
    print(f"[+] Evidence ID: {record.evidence_id}")
    print(f"[+] File: {record.manifest.files[0].name}")
    print(f"[+] Size: {record.manifest.files[0].size} bytes")
    print(
        "[+] SHA-256 integrity fingerprint registered: "
        f"{record.manifest.files[0].sha256}"
    )
    print(f"[+] Original evidence preserved: {record.original_path}")
    print(
        "[+] Application-level write protection enabled: "
        f"{record.manifest.originals_read_only}"
    )
    print(f"[+] Working copy created: {record.working_path}")

    for name, _, written in record.package_members:
        print(f"[+] Package member extracted: {name} ({written} bytes)")

    print(f"[+] Manifest generated: {intake.manifest_path(record.evidence_id)}")
    print(
        f"[+] Provenance recorded: "
        f"{intake.provenance_path(record.evidence_id)}"
    )

    if record.provenance.unavailable_fields:
        print(
            "[!] Unavailable provenance fields: "
            + ", ".join(record.provenance.unavailable_fields)
        )

    print(f"[+] Integrity status: {record.integrity.status.value}")

    print(
        "[i] Locally stored evidence is not made physically immutable by "
        "this step: it is a registered SHA-256 fingerprint, and the original "
        "is preserved with application-level write protection only. A "
        "privileged filesystem user can still modify both the evidence and "
        "its manifest."
    )

    return 0 if record.verified else 1


def _run_verify(args: argparse.Namespace) -> int:
    intake = EvidenceIntake(root=args.root)

    if args.evidence_id:
        targets = [args.evidence_id]
    else:
        targets = intake.workspace.list_evidence_ids()

    if not targets:
        print("[!] No registered evidence to verify")

        return 0

    failed = False

    for evidence_id in targets:
        print(f"[+] Verifying {evidence_id}")

        for result in intake.verify(evidence_id):
            print(f"  {Path(result.path).name}: {result.status.value}")

            if result.expected_sha256:
                print(f"    Expected SHA-256: {result.expected_sha256}")

            if result.observed_sha256:
                print(f"    Observed SHA-256: {result.observed_sha256}")

            if not result.verified:
                failed = True

    return 1 if failed else 0


def main(argv: Optional[Sequence[str]] = None) -> int:
    """Entry point for ``python -m framework.evidence.intake``."""

    arguments = list(sys.argv[1:] if argv is None else argv)

    # Bare `python -m framework.evidence.intake <file>` is the documented
    # shorthand for the `intake` sub-command.
    if arguments and arguments[0] not in ("intake", "verify", "-h", "--help"):
        arguments.insert(0, "intake")

    parser = _build_parser()
    args = parser.parse_args(arguments)

    if not args.command:
        parser.print_help()

        return 1

    try:
        if args.command == "intake":
            return _run_intake(args)

        return _run_verify(args)
    except EvidenceError as error:
        print(f"[!] {type(error).__name__}: {error}", file=sys.stderr)

        return 2


if __name__ == "__main__":
    sys.exit(main())
