@dataclass(frozen=True)
class EvidenceWorkspace:
    """Filesystem layout of the evidence store.

    The store is a plain directory tree so an examiner can inspect it with
    ordinary tools. Nothing here is a database and nothing is required for
    verification beyond a preserved original and its manifest.
    """

    root: Path

    @classmethod
    def at(cls, root: Union[str, Path] = DEFAULT_WORKSPACE_ROOT) -> "EvidenceWorkspace":
        return cls(root=Path(root).expanduser())

    @property
    def originals_dir(self) -> Path:
        return self.root / "originals"

    @property
    def manifests_dir(self) -> Path:
        return self.root / "manifests"

    @property
    def provenance_dir(self) -> Path:
        return self.root / "provenance"

    @property
    def working_dir(self) -> Path:
        return self.root / "working"

    def evidence_dir(self, evidence_id: str) -> Path:
        return self.originals_dir / path_safe_name(evidence_id)

    def manifest_path(self, evidence_id: str) -> Path:
        return self.manifests_dir / (
            f"{path_safe_name(evidence_id)}{MANIFEST_SUFFIX}"
        )

    def provenance_path(self, evidence_id: str) -> Path:
        return self.provenance_dir / (
            f"{path_safe_name(evidence_id)}{PROVENANCE_SUFFIX}"
        )

    def working_copy_path(self, evidence_id: str, filename: str) -> Path:
        return (
            self.working_dir
            / path_safe_name(evidence_id)
            / _WORKING_COPY_DIRNAME
            / path_safe_name(filename)
        )

    def package_dir(self, evidence_id: str) -> Path:
        return (
            self.working_dir
            / path_safe_name(evidence_id)
            / _PACKAGE_DIRNAME
        )

    def ensure(self) -> "EvidenceWorkspace":
        """Create the directory skeleton if it is absent."""

        for directory in (
            self.root,
            self.originals_dir,
            self.manifests_dir,
            self.provenance_dir,
            self.working_dir,
        ):
            directory.mkdir(parents=True, exist_ok=True)

        return self

    def list_evidence_ids(self) -> list:
        """Registered evidence identifiers, newest first."""

        if not self.manifests_dir.is_dir():
            return []

        identifiers = [
            item.name[: -len(MANIFEST_SUFFIX)]
            for item in sorted(self.manifests_dir.glob(f"*{MANIFEST_SUFFIX}"))
            if item.is_file()
        ]

        return sorted(identifiers, reverse=True)


