DEFAULT_WORKSPACE_ROOT = "data/evidence"

# Conservative archive limits. A legitimate SOC evidence package is orders of
# magnitude below these; they exist to bound a hostile or accidental bomb.
MAX_ARCHIVE_MEMBERS = 10_000
MAX_ARCHIVE_TOTAL_BYTES = 4 * 1024 * 1024 * 1024
MAX_ARCHIVE_MEMBER_BYTES = 1 * 1024 * 1024 * 1024
MAX_MEMBER_PATH_DEPTH = 32
MAX_MEMBER_NAME_LENGTH = 255

_WINDOWS_DRIVE = re.compile(r"\A[A-Za-z]:")

# An evidence ID is an opaque token generated by this package, never a path.
# It is validated against this pattern before it is ever joined to a
# directory, so a user-supplied ID cannot traverse, inject an absolute path,
# or select an arbitrary working copy.
_EVIDENCE_ID_PATTERN = re.compile(r"\A[A-Za-z0-9][A-Za-z0-9._-]{0,119}\Z")

_ENCRYPTED_FLAG = 0x1

_WORKING_COPY_DIRNAME = "dataset"
_PACKAGE_DIRNAME = "package"


# ---------------------------------------------------------------------------
# Analysis-resolution errors
# ---------------------------------------------------------------------------


class EvidenceResolutionError(EvidenceError):
    """Raised when an evidence ID cannot be resolved to a usable working copy."""


class EvidenceIntegrityError(EvidenceError):
    """Raised when registered evidence fails verification before analysis.

    The full comparison is carried on the exception so the caller can report
    the expected and observed digests without re-hashing anything.
    """

    def __init__(
        self,
        result: IntegrityResult,
        subject: str = "preserved original",
    ):
        self.result = result
        self.subject = subject

        super().__init__(
            f"{subject} failed integrity verification: {result.status.value}"
        )


def validate_evidence_id(evidence_id: Union[str, None]) -> str:
    """Validate an opaque evidence identifier.

    Rejects empty values, path separators, ``..``, absolute paths, drive
    letters, null bytes and anything outside the generated token alphabet.
    A rejected ID never reaches the filesystem.

    Raises:
        EvidenceNotFoundError: no identifier was supplied.
        EvidenceValidationError: the value is not a plain evidence token.
    """

    token = str(evidence_id if evidence_id is not None else "").strip()

    if not token:
        raise EvidenceNotFoundError("An evidence ID is required")

    if not _EVIDENCE_ID_PATTERN.match(token) or ".." in token:
        raise EvidenceValidationError(
            f"Refusing to resolve a value that is not an evidence "
            f"identifier: {evidence_id!r}"
        )

    return token


