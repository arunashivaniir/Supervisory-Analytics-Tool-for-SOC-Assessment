@dataclass
class EvidenceRecord:
    """Everything intake established about a single submission."""

    evidence_id: str
    original_path: Path
    working_path: Path
    manifest: EvidenceManifest
    provenance: ProvenanceRecord
    integrity: IntegrityResult
    package_members: list = field(default_factory=list)
    workspace: Optional[EvidenceWorkspace] = None

    @property
    def verified(self) -> bool:
        return self.integrity.verified

    def to_dict(self) -> dict:
        return {
            "evidence_id": self.evidence_id,
            "original_path": str(self.original_path),
            "working_path": str(self.working_path),
            "originals_read_only": self.manifest.originals_read_only,
            "manifest": self.manifest.to_dict(),
            "provenance": self.provenance.to_dict(),
            "integrity": self.integrity.to_dict(),
            "package_members": [
                {"name": name, "size": size}
                for name, _, size in self.package_members
            ],
        }


@dataclass(frozen=True)
class ResolvedEvidence:
    """A registered submission resolved to a verified analysis target.

    Produced only after the preserved original has been verified against its
    registered digest. ``working_path`` is the artefact a downstream analytics
    layer may read; ``original_path`` is never handed out for analysis.
    """

    evidence_id: str
    original_path: Path
    working_path: Path
    manifest: EvidenceManifest
    provenance: Optional[ProvenanceRecord]
    original_integrity: IntegrityResult
    working_integrity: IntegrityResult

    @property
    def verified(self) -> bool:
        return (
            self.original_integrity.verified and self.working_integrity.verified
        )

    def to_dict(self) -> dict:
        return {
            "evidence_id": self.evidence_id,
            "original_path": str(self.original_path),
            "working_path": str(self.working_path),
            "original_integrity": self.original_integrity.to_dict(),
            "working_integrity": self.working_integrity.to_dict(),
        }


