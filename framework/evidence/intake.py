class EvidenceIntake:
    """Register submitted evidence and produce a controlled analysis copy."""

    def __init__(
        self,
        root: Union[str, Path] = DEFAULT_WORKSPACE_ROOT,
    ):
        self.workspace = EvidenceWorkspace.at(root).ensure()

    # -- layout helpers ---------------------------------------------------

    @property
    def root(self) -> Path:
        return self.workspace.root

    def manifest_path(self, evidence_id: str) -> Path:
        return self.workspace.manifest_path(evidence_id)

    def provenance_path(self, evidence_id: str) -> Path:
        return self.workspace.provenance_path(evidence_id)

    # -- validation -------------------------------------------------------

    def validate_source(
        self,
        source: Union[str, Path],
        allow_symlink: bool = False,
    ) -> Path:
        """Validate a submitted path and return its resolved location."""

        path = Path(source).expanduser()

        if not path.exists():
            raise EvidenceNotFoundError(f"Evidence path not found: {path}")

        if path.is_symlink() and not allow_symlink:
            raise EvidenceValidationError(
                f"Evidence path is a symbolic link and was refused: {path}"
            )

        if not path.is_file():
            raise EvidenceValidationError(
                f"Evidence path is not a regular file: {path}"
            )

        resolved = path.resolve()

        originals_root = self.workspace.originals_dir.resolve()

        if resolved == originals_root or originals_root in resolved.parents:
            raise EvidenceValidationError(
                "Preserved evidence cannot be re-registered as a new "
                f"submission: {resolved}"
            )

        return resolved

    # -- registration -----------------------------------------------------

    def intake(
        self,
        source: Union[str, Path],
        source_identifier: Optional[str] = None,
        assessment_period: Optional[str] = None,
        submitted_by: Optional[str] = None,
        received_channel: Optional[str] = None,
        extract_package: bool = True,
        metadata: Optional[dict] = None,
        allow_symlink: bool = False,
        allow_duplicate: bool = False,
    ) -> EvidenceRecord:
        """Register one evidence file or ZIP package.

        Steps: validate path, inspect metadata, hash, reject a byte-identical
        re-submission, allocate an evidence ID, preserve the original, create
        the working copy, validate/extract a package if applicable, write
        manifest and provenance, then re-verify the preserved original against
        the recorded digest.

        Descriptive context (entity identifier, assessment period, submitter) is
        optional and is stored only if supplied.
        """

        received_at = utc_now()
        path = self.validate_source(source, allow_symlink=allow_symlink)

        observed_hash = calculate_sha256(path)
        size = path.stat().st_size
        stored_name = path_safe_name(path.name)
        content_type = classify_file(path)

        if not allow_duplicate:
            duplicate = self.find_registered_digest(observed_hash)

            if duplicate is not None:
                raise EvidenceConflictError(
                    "Byte-identical evidence is already registered as "
                    f"{duplicate['evidence_id']} (received "
                    f"{duplicate['created_at']}). An existing submission is "
                    "never replaced; verify the registered evidence instead, "
                    "or pass allow_duplicate=True to register a second copy."
                )

        evidence_id = self._allocate_evidence_id(observed_hash, received_at)

        working_path = self.workspace.working_copy_path(evidence_id, stored_name)

        manifest_file = self.manifest_path(evidence_id)
        provenance_file = self.provenance_path(evidence_id)
        evidence_dir = self.workspace.evidence_dir(evidence_id)

        try:
            original_path, read_only = self._preserve_original(
                path,
                evidence_dir,
                stored_name,
                observed_hash,
            )

            self._create_working_copy(original_path, working_path, observed_hash)

            package_members = self._register_package(
                path,
                evidence_id,
                content_type,
                extract_package=extract_package,
            )

            manifest = build_manifest(
                evidence_id=evidence_id,
                files=self._manifest_entries(
                    path=path,
                    stored_name=stored_name,
                    size=size,
                    sha256=observed_hash,
                    content_type=content_type,
                    package_members=package_members,
                ),
                created_at=utc_now_iso(),
                originals_read_only=read_only,
                notes={
                    "intake": "sat-sa-evidence-intake/1.0",
                    "original_filename": path.name,
                    "content_type": content_type,
                },
            )

            save_manifest(manifest, manifest_file)

            provenance = build_provenance(
                evidence_id=evidence_id,
                received_at=received_at.isoformat(timespec="seconds").replace(
                    "+00:00", "Z"
                ),
                original_filename=path.name,
                file_size=size,
                sha256=observed_hash,
                package_type=content_type,
                source_identifier=source_identifier,
                assessment_period=assessment_period,
                submitted_by=submitted_by,
                received_channel=received_channel,
                status=STATUS_REGISTERED,
                metadata=metadata,
            )

            provenance.add_custody_event(
                action="EVIDENCE_RECEIVED",
                detail=f"Registered {len(manifest.files)} file(s) from "
                f"{path.name}",
            )
            provenance.add_custody_event(
                action="ORIGINAL_PRESERVED",
                detail=f"Original evidence preserved; application-level write "
                f"protection enabled: {read_only}. This is a handling control, "
                f"not a cryptographic guarantee.",
            )
            provenance.add_custody_event(
                action="ANALYSIS_COPY_CREATED",
                detail=f"Working copy available for the SAT-SA pipeline: "
                f"{working_path}",
            )

            save_provenance(provenance, provenance_file)

            integrity = verify_sha256(original_path, manifest.files[0].sha256)

            if not integrity.verified:
                raise EvidenceValidationError(
                    "Preserved original failed immediate re-verification: "
                    f"{integrity.status.value}"
                )

        except Exception:
            self._discard(evidence_id)
            raise

        return EvidenceRecord(
            evidence_id=evidence_id,
            original_path=original_path,
            working_path=working_path,
            manifest=manifest,
            provenance=provenance,
            integrity=integrity,
            package_members=package_members,
            workspace=self.workspace,
        )

    # -- verification -----------------------------------------------------

    def verify(self, evidence_id: str) -> list:
        """Re-verify every registered file of a submission against its manifest.

        Returns one :class:`IntegrityResult` per manifest entry.
        """

        manifest = load_manifest(self.manifest_path(evidence_id))

        return manifest.verify(self.verification_roots(evidence_id))

    def verification_roots(self, evidence_id: str) -> dict:
        """Base directories a manifest's recorded locations resolve against."""

        identifier = path_safe_name(evidence_id)

        return {
            LOCATION_ORIGINALS: self.workspace.evidence_dir(identifier),
            LOCATION_WORKING: self.workspace.working_dir / identifier,
        }

    def verify_all(self) -> dict:
        """Re-verify every registered submission, keyed by evidence ID."""

        return {
            evidence_id: [
                result.to_dict()
                for result in self.verify(evidence_id)
            ]
            for evidence_id in self.workspace.list_evidence_ids()
        }

    def load_manifest(self, evidence_id: str) -> EvidenceManifest:
        return load_manifest(self.manifest_path(evidence_id))

    def find_registered_digest(self, sha256: str) -> Optional[dict]:
        """Locate an already registered submission with this exact digest.

        The evidence ID contains a timestamp, so identical content submitted
        later would receive a different identifier. Comparing digests is what
        makes duplicate detection independent of clock resolution.
        """

        for evidence_id in self.workspace.list_evidence_ids():
            try:
                manifest = load_manifest(self.manifest_path(evidence_id))
            except EvidenceError:
                continue

            for entry in manifest.files:
                if entry.role == "original" and entry.sha256 == sha256:
                    return {
                        "evidence_id": evidence_id,
                        "name": entry.name,
                        "created_at": manifest.created_at,
                    }

        return None

    def load_provenance(self, evidence_id: str) -> ProvenanceRecord:
        return load_provenance(self.provenance_path(evidence_id))

    # -- analysis resolution ----------------------------------------------

    def resolve_evidence_id(self, evidence_id: str) -> str:
        """Validate an evidence ID and confirm it is registered.

        This performs no analysis and no hashing: it only establishes that the
        identifier is a well-formed token and that a manifest exists for it.

        Raises:
            EvidenceNotFoundError: no identifier supplied, or nothing is
                registered under it.
            EvidenceValidationError: the value is not a plain evidence token.
        """

        identifier = validate_evidence_id(evidence_id)

        if not self.manifest_path(identifier).is_file():
            raise EvidenceNotFoundError(
                f"No evidence registration found for {identifier} in "
                f"{self.workspace.root}"
            )

        return identifier

    def verify_analysis_target(self, evidence_id: str) -> ResolvedEvidence:
        """Verify registered evidence and return its controlled working copy.

        Order of operations, all of it before any analysis may start:

        1. load the registered manifest for the (already validated) ID;
        2. verify the preserved original against its registered digest;
        3. resolve the working copy the workspace created at intake;
        4. verify the working copy still matches the registered digest.

        Any non-``VERIFIED`` outcome raises :class:`EvidenceIntegrityError`
        carrying the full comparison. The preserved original is never returned
        as an analysis target.

        Raises:
            EvidenceNotFoundError: the ID is not registered.
            EvidenceResolutionError: the registration is structurally unusable.
            EvidenceIntegrityError: verification did not succeed.
        """

        identifier = self.resolve_evidence_id(evidence_id)
        manifest = self.load_manifest(identifier)

        original_entry = next(
            (entry for entry in manifest.files if entry.role == "original"),
            None,
        )

        if original_entry is None:
            raise EvidenceResolutionError(
                f"{identifier} registers no preserved original"
            )

        original_path = resolve_within(
            self.workspace.evidence_dir(identifier),
            original_entry.relative_path,
        )

        original_integrity = verify_sha256(
            original_path, original_entry.sha256
        )

        if not original_integrity.verified:
            raise EvidenceIntegrityError(
                original_integrity, subject="preserved original"
            )

        working_path = resolve_within(
            self.workspace.working_dir / identifier,
            (
                Path(_WORKING_COPY_DIRNAME)
                / path_safe_name(original_entry.stored_name)
            ).as_posix(),
        )

        if not working_path.is_file():
            raise EvidenceResolutionError(
                f"{identifier} has no controlled working copy at "
                f"{working_path}; re-register the evidence before analysis"
            )

        working_integrity = verify_sha256(
            working_path, original_entry.sha256
        )

        if not working_integrity.verified:
            raise EvidenceIntegrityError(
                working_integrity, subject="controlled working copy"
            )

        try:
            provenance = self.load_provenance(identifier)
        except EvidenceError:
            provenance = None

        return ResolvedEvidence(
            evidence_id=identifier,
            original_path=original_path,
            working_path=working_path,
            manifest=manifest,
            provenance=provenance,
            original_integrity=original_integrity,
            working_integrity=working_integrity,
        )

    def resolve_analysis_target(self, evidence_id: str) -> ResolvedEvidence:
        """Convenience wrapper: validate, verify, and return the target."""

        return self.verify_analysis_target(evidence_id)

    def list_evidence(self) -> list:
        """Metadata-only inventory of registered submissions."""

        inventory: list = []

        for evidence_id in self.workspace.list_evidence_ids():
            entry = {"evidence_id": evidence_id}

            try:
                manifest = self.load_manifest(evidence_id)
            except EvidenceError:
                entry["status"] = IntegrityStatus.UNAVAILABLE.value
                inventory.append(entry)
                continue

            entry["created_at"] = manifest.created_at
            entry["file_count"] = manifest.file_count
            entry["total_size"] = manifest.total_size
            entry["files"] = [
                {
                    "name": item.name,
                    "size": item.size,
                    "sha256": item.sha256,
                    "content_type": item.content_type,
                }
                for item in manifest.files
            ]

            statuses = {
                result.status.value
                for result in self.verify(evidence_id)
            }

            entry["integrity"] = (
                "VERIFIED"
                if statuses == {IntegrityStatus.VERIFIED.value}
                else sorted(statuses)
            )

            inventory.append(entry)

        return inventory

    # -- internals --------------------------------------------------------

    def _allocate_evidence_id(
        self,
        sha256: str,
        received_at,
    ) -> str:
        """Return an evidence identifier that is not yet in use.

        The base identifier is derived from the digest and the registration
        moment, so it is normally free. If it is already taken -- two distinct
        submissions inside the same second, or an explicitly permitted
        duplicate -- a numeric suffix is appended rather than overwriting the
        existing registration.
        """

        base = generate_evidence_id(sha256, received_at)
        candidate = base
        attempt = 1

        while self._is_registered(candidate):
            attempt += 1
            candidate = f"{base}-{attempt}"

        return candidate

    def _is_registered(self, evidence_id: str) -> bool:
        return any(
            occupied.exists()
            for occupied in (
                self.workspace.evidence_dir(evidence_id),
                self.manifest_path(evidence_id),
                self.provenance_path(evidence_id),
            )
        )

    def _preserve_original(
        self,
        path: Path,
        evidence_dir: Path,
        stored_name: str,
        expected_hash: str,
    ) -> tuple:
        """Copy evidence into the originals area and protect it from writes.

        The copy is hashed as it is written, so the digest recorded later is the
        digest of the bytes actually on disk.
        """

        evidence_dir.mkdir(parents=True, exist_ok=True)

        destination = evidence_dir / stored_name

        if destination.exists():
            raise EvidenceConflictError(
                f"Refusing to overwrite existing original evidence: "
                f"{destination}"
            )

        written, copied_hash = copy_and_hash(path, destination)

        if copied_hash != expected_hash:
            raise EvidenceValidationError(
                "Evidence changed while it was being registered; the "
                "submission was rejected and nothing was preserved"
            )

        read_only = _set_read_only(destination)

        return destination, read_only

    def _create_working_copy(
        self,
        original_path: Path,
        working_path: Path,
        expected_hash: str,
    ) -> None:
        """Create the separate, writable analysis copy of the original.

        The working copy is the only artefact the SAT-SA pipeline is meant to
        read. It is deliberately a distinct file so that analysis can never
        alter the preserved original by accident.
        """

        working_path.parent.mkdir(parents=True, exist_ok=True)

        if working_path.exists():
            raise EvidenceConflictError(
                f"Refusing to overwrite an existing analysis copy: "
                f"{working_path}"
            )

        # A write-protected original is not opened for writing, so the copy is
        # made from the source bytes and re-checked against the digest.
        with open(working_path, "xb") as writer:
            with original_path.open("rb") as reader:
                shutil.copyfileobj(reader, writer, DEFAULT_CHUNK_SIZE)

        observed = calculate_sha256(working_path)

        if observed != expected_hash:
            working_path.unlink(missing_ok=True)
            raise EvidenceValidationError(
                "Working copy did not match the registered digest"
            )

    def _register_package(
        self,
        path: Path,
        evidence_id: str,
        content_type: str,
        extract_package: bool,
    ) -> list:
        """Validate a ZIP package and extract it into the working area.

        The package itself is already registered and hashed as the original;
        this step only handles the members it contains.
        """

        if content_type != "zip":
            return []

        accepted = validate_package(path)

        members: list = []

        if extract_package:
            destination = self.workspace.package_dir(evidence_id)
            members = _extract_package(path, destination, accepted)

        return members

    def _manifest_entries(
        self,
        path: Path,
        stored_name: str,
        size: int,
        sha256: str,
        content_type: str,
        package_members: Sequence,
    ) -> list:
        entries = [
            ManifestFile(
                name=path.name,
                stored_name=stored_name,
                relative_path=stored_name,
                size=int(size),
                sha256=sha256,
                modified_at=file_mtime_iso(path),
                content_type=content_type,
                role="original",
                location=LOCATION_ORIGINALS,
            )
        ]

        for name, target, written in package_members:
            relative = (
                Path(_PACKAGE_DIRNAME) / Path(name).as_posix()
            ).as_posix()

            entries.append(
                ManifestFile(
                    name=name,
                    stored_name=Path(name).name,
                    relative_path=relative,
                    size=int(written),
                    sha256=calculate_sha256(target),
                    modified_at=file_mtime_iso(target),
                    content_type=classify_file(target),
                    role="extracted",
                    location=LOCATION_WORKING,
                )
            )

        return entries

    def _discard(self, evidence_id: str) -> None:
        """Remove a partially written submission after a failed intake."""

        for directory in (
            self.workspace.evidence_dir(evidence_id),
            self.workspace.working_dir / path_safe_name(evidence_id),
        ):
            if not directory.exists():
                continue

            for path in sorted(directory.rglob("*"), reverse=True):
                try:
                    if path.is_file():
                        _set_writable(path)
                        path.unlink()
                    elif path.is_dir():
                        path.rmdir()
                except OSError:
                    pass

            try:
                directory.rmdir()
            except OSError:
                pass

        for record in (
            self.manifest_path(evidence_id),
            self.provenance_path(evidence_id),
        ):
            try:
                record.unlink(missing_ok=True)
            except OSError:
                pass


def _set_read_only(path: Path) -> bool:
    """Application-level write protection for a preserved original.

    This clears the owner write bit so a well-behaved process does not
    overwrite registered evidence by accident. It is a *handling control*, not
    a security boundary and not a cryptographic one: the owning account can
    restore the bit, and a privileged filesystem user can modify the evidence
    file and the local manifest that records its digest.

    The control that actually detects change is the registered SHA-256 digest,
    compared during verification. See ``docs/evidence_integrity.md``.
    """

    try:
        current = path.stat().st_mode
        path.chmod(stat.S_IMODE(current) & ~0o222)
        return True
    except OSError:
        return False


def _set_writable(path: Path) -> None:
    try:
        current = path.stat().st_mode
        path.chmod(stat.S_IMODE(current) | 0o200)
    except OSError:
        pass


def unlock_preserved_original(path: Union[str, Path]) -> Path:
    """Restore owner-write permission on a preserved original.

    Maintenance and demonstration only: an examiner may need to restore write
    access in order to prove that a recorded digest detects modification. This
    is deliberately an explicit, named action rather than something intake does
    automatically.
    """

    target = Path(path).expanduser()

    if not target.is_file():
        raise EvidenceNotFoundError(f"Evidence file not found: {target}")

    _set_writable(target)

    return target


def intake_file(
    source: Union[str, Path],
    root: Union[str, Path] = DEFAULT_WORKSPACE_ROOT,
    **options,
) -> EvidenceRecord:
    """Convenience wrapper: register one submission into a workspace."""

    return EvidenceIntake(root=root).intake(source, **options)

